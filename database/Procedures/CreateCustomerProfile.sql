-- PURPOSE: Creates a customer profile and its associated user login record.
ALTER PROCEDURE [dbo].[CreateCustomerProfile]
@FullName VARCHAR(50),
@Email VARCHAR(100),
@PhoneNumber VARCHAR(10),
@Username VARCHAR(50),
@PasswordHash VARCHAR(255)
AS
BEGIN 
  BEGIN TRY
    BEGIN TRANSACTION;

    -- Check whether the supplied email address is already registered.
    IF EXISTS (
        SELECT 1
        FROM Customers
        WHERE Email = @Email
    )
    BEGIN
        RAISERROR('Email already exists.',16,1);
        ROLLBACK;
        RETURN;
    END

    -- Check whether the requested username is already assigned to a user.
    IF EXISTS (
        SELECT 1
        FROM Users
        WHERE Username = @Username
    )
    BEGIN
        RAISERROR('Username already exists.',16,1);
        ROLLBACK;
        RETURN;
    END

    -- Insert the customer's personal details into the Customers table.
    INSERT INTO Customers(FullName,Email,PhoneNumber)
    VALUES(@FullName,@Email,@PhoneNumber);

    -- Retrieve the CustomerId generated by the preceding INSERT statement.
    DECLARE @CustomerId INT = SCOPE_IDENTITY();

     -- Create the user's login record using the newly generated CustomerId.
    INSERT INTO Users
    (CustomerId, Username, PasswordHash)
    VALUES(@CustomerId,@Username, @PasswordHash);

    -- Return the newly created CustomerId to the calling application allowing the application to identify the registered customer.
    SELECT @CustomerId AS CustomerId;

    -- Commit the transaction after both the customer and user records have been inserted successfully
    COMMIT;
    PRINT 'Customer profile created successfully';
 END TRY
 BEGIN CATCH
    -- Roll back any active transaction if an error occurs, preventing incomplete registration from being committed.
    IF @@TRANCOUNT > 0
    ROLLBACK;
    PRINT ERROR_MESSAGE();
END CATCH
END;
