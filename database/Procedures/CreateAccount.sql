-- PURPOSE: Creates a bank account for an existing customer.
ALTER PROCEDURE [dbo].[CreateAccount]
@CustomerId INT
AS
BEGIN
 BEGIN TRY
   BEGIN TRANSACTION;

    -- Validate that the supplied customer ID exists in the Customers table.
    IF NOT EXISTS
    (SELECT 1
     FROM Customers
     WHERE CustomerId = @CustomerId
    )
    BEGIN
        RAISERROR('Customer does not exist.',16,1);
        ROLLBACK;
        RETURN;
    END

    -- Enforce the business rule that each customer may have only one account.
    IF EXISTS
    (SELECT 1
     FROM Accounts
     WHERE CustomerId = @CustomerId
     )
    BEGIN
        RAISERROR('Customer already has an account.',16,1);
        ROLLBACK;
        RETURN;
    END
     
    -- Insert the new account record for the validated customer.
    INSERT INTO Accounts(CustomerId)
    VALUES(@CustomerId);

    -- Retrieve the AccountId generated by the preceding INSERT statement.
    DECLARE @AccountId INT = SCOPE_IDENTITY();

    -- Generate a 10-digit account number using the new AccountId.
    UPDATE Accounts
    SET AccountNumber = RIGHT(
    CAST(1000000000 + @AccountId AS VARCHAR(10)),
    10
    )
    WHERE AccountId = @AccountId;

    -- Commit the transaction after the account has been created and updated.
    COMMIT;
    PRINT 'Account created successfully';
END TRY
BEGIN CATCH
     -- Roll back any active transaction if an error occurs.
    IF @@TRANCOUNT > 0
    ROLLBACK;

    -- Display the error message for troubleshooting.
    PRINT ERROR_MESSAGE();
END CATCH
END;
 
